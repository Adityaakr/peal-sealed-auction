/**
 * gen-abi.ts - write client/abi.ts from the Foundry build artifacts.
 * Run after `forge build`: `npm run abi`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const contracts = ["SealedAuction", "CommitteeRegistry", "SealedAuctionFactory", "PealT", "DemoFaucet"];

let out = "// Generated by scripts/gen-abi.ts from the Foundry artifacts. Do not edit.\n\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")) as {
    abi: unknown;
    bytecode: { object: string };
  };
  out += `export const ${name[0]!.toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "client", "abi.ts"), out);
console.log(`wrote client/abi.ts (${contracts.join(", ")})`);
